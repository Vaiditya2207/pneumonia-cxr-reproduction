"""Fill the Milestone 4 macro block in paper.tex from ../results/ablation_all.json.

Usage (from milestone5/):  ../.venv/bin/python fill_macros.py && tectonic paper.tex
Without the JSON every macro is set to TBD so the paper still compiles.
"""
import json, os, re
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.environ.get("ABL_JSON", os.path.join(HERE, "..", "results", "ablation_all.json"))
TEX = os.path.join(HERE, "paper.tex")
BEGIN, END = "%% BEGIN M4 MACROS (generated by fill_macros.py)", "%% END M4 MACROS"

CONFIGS = {"0": "Zero", "1": "One", "2": "Two", "all": "All"}
METRICS = {"accuracy": "Acc", "sensitivity": "Sens", "specificity": "Spec",
           "precision": "Prec", "auc": "AUC", "train_acc": "Train", "val_acc": "Val"}


def fmt(vals):
    vals = np.asarray(vals, float)
    return f"{vals.mean():.2f}" if len(vals) == 1 else f"{vals.mean():.2f}$\\pm${vals.std():.2f}"


def build():
    m = {}
    if not os.path.exists(JSON):
        for c in CONFIGS.values():
            for k in METRICS.values():
                m[f"Abl{c}{k}"] = "TBD"
            m[f"Abl{c}Seeds"] = "TBD"
        for k in ["DAUC", "DSpec", "DSens", "DAcc", "FPZero", "FPTwo", "FNZero", "FNTwo",
                  "VerdictAUC", "VerdictSpec", "VerdictSens", "VerdictOverall", "OutcomeSummary"]:
            m[k] = "TBD"
        m["MFilled"] = "no"
        return m

    R = json.load(open(JSON))
    mean = {}
    for key, c in CONFIGS.items():
        runs = R.get(key, [])
        m[f"Abl{c}Seeds"] = str(len(runs)) if runs else "TBD"
        for mk, k in METRICS.items():
            vals = [r[mk] for r in runs if mk in r]
            m[f"Abl{c}{k}"] = fmt(vals) if vals else "TBD"
            if vals:
                mean[(key, mk)] = float(np.mean(vals))
        if runs:  # seed-0 run is first
            m[f"FP{c}"], m[f"FN{c}"] = str(runs[0]["fp"]), str(runs[0]["fn"])
    d = {k: mean[("2", k)] - mean[("0", k)] for k in ["auc", "specificity", "sensitivity", "accuracy"]}
    s = lambda v: f"{v:+.2f}"
    m.update(DAUC=s(d["auc"]), DSpec=s(d["specificity"]), DSens=s(d["sensitivity"]), DAcc=s(d["accuracy"]))

    # Pre-registered criteria (milestone3/hypothesis.md); "noise" = baseline seed std of AUC
    auc_std0 = float(np.std([r["auc"] for r in R["0"]]))
    ok_auc = d["auc"] > max(0.5, 2 * auc_std0)
    ok_spec = d["specificity"] > 0 and d["specificity"] >= max(d["sensitivity"], d["auc"])
    ok_sens = abs(d["sensitivity"]) <= 1.5
    yes = lambda b: "supported" if b else "not supported"
    m.update(VerdictAUC=yes(ok_auc), VerdictSpec=yes(ok_spec), VerdictSens=yes(ok_sens))
    overall = ("supported" if ok_auc and ok_spec and ok_sens else
               "partly supported" if ok_auc or ok_spec else "falsified")
    m["VerdictOverall"] = overall
    m["OutcomeSummary"] = (
        f"Unfreezing two blocks changed AUC by {s(d['auc'])} points, specificity by {s(d['specificity'])} "
        f"and sensitivity by {s(d['sensitivity'])} points (mean over seeds, versus the frozen baseline). "
        f"Judged against the criteria we wrote down before the experiment, the hypothesis is \\textbf{{{overall}}}.")
    m["MFilled"] = "yes"
    return m


def main():
    m = build()
    block = BEGIN + "\n" + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()) + "\n" + END
    tex = open(TEX).read()
    tex = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, tex, flags=re.S)
    open(TEX, "w").write(tex)
    print("filled from JSON" if m["MFilled"] == "yes" else "JSON missing: macros set to TBD")
    for k in ["DAUC", "DSpec", "DSens", "VerdictOverall"]:
        print(f"  {k} = {m[k]}")


if __name__ == "__main__":
    main()
